// "Free ขึ้นไป คือใช้ได้ทุกแผน รวมถึงแผน Free ที่ทดลองใช้ได้ 30 วัน" เมื่อทุกแผนมีจริง · ไม่อย่างนั้นบอกเฉพาะแผนที่มี
function lawPlans(P) {
  const from = P.planFrom('laws');
  const all = P.PLANS.every((p) => P.hasItem(p.key, 'laws') && P.hasItem(p.key, 'standards'));
  const free = P.PLANS.find((p) => p.yearly === 0);
  return all ? `${from} คือใช้ได้ทุกแผน${free ? ` รวมถึงแผน ${free.name} ที่ทดลองใช้ได้ 30 วัน` : ''}` : from;
}

